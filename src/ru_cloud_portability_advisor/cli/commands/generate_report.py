from __future__ import annotations

import json
from pathlib import Path
from typing import Optional

import typer
from rich.console import Console

from ru_cloud_portability_advisor.render.html_report import render_html
from ru_cloud_portability_advisor.render.markdown_report import render_markdown

console = Console()


def generate_report(
    input: Path = typer.Option(..., "--input", "-i", help="Path to JSON report generated by analyze-project"),
    format: str = typer.Option("markdown", "--format", "-f", help="Output format: markdown|html|json"),
    output: Optional[Path] = typer.Option(None, "--output", "-o", help="Optional output file"),
) -> None:
    data = json.loads(input.read_text(encoding="utf-8"))
    if format == "markdown":
        rendered = render_markdown(data)
    elif format == "html":
        rendered = render_html(data)
    elif format == "json":
        rendered = json.dumps(data, indent=2, ensure_ascii=False)
    else:
        console.print(f"[red]Неподдерживаемый формат: {format}[/red]")
        raise typer.Exit(code=1)

    if output:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(rendered, encoding="utf-8")
        console.print(f"[green]Файл сохранен:[/green] {output}")
    else:
        console.print(rendered)

